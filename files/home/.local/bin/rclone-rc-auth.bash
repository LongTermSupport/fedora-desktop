# shellcheck shell=bash
#
# rclone remote-control credentials — SOURCED LIBRARY, never executed.
#
# Source it, then call `rclone_rc` wherever you would have called `rclone rc`:
#
#     . "$HOME/.local/bin/rclone-rc-auth.bash"
#     json=$(rclone_rc --url="http://localhost:5572" vfs/stats) || exit 1
#
# WHY THIS EXISTS
# ---------------
# Plan 00067 gave the mount units --rc-user/--rc-pass (supplied as
# RCLONE_RC_USER/RCLONE_RC_PASS through a systemd EnvironmentFile). It did so
# believing that core/stats and vfs/stats "answer unauthenticated" and that
# only the vfs/refresh caller needed migrating. That premise is FALSE: once a
# credential is configured, rclone gates EVERY rc endpoint, and an
# unauthenticated call gets HTTP 401. Every un-migrated client broke silently.
#
# The migration was then hand-copied into two scripts and missed in two more.
# This library exists so there is ONE place that knows how to authenticate —
# the divergence was the defect, so a fourth copy of the block would have
# reproduced its cause.
#
# CREDENTIALS GO IN THE ENVIRONMENT, NOT IN argv
# ----------------------------------------------
# The client-side flags are --user/--pass (note: differently named from the
# server-side --rc-user/--rc-pass). Passing them on the command line puts the
# password in `ps` output for every user on the box. rclone maps each flag to
# an RCLONE_<FLAG> environment variable, so --user/--pass are driven by
# RCLONE_USER/RCLONE_PASS instead, scoped to the single child process.
#
# The credential file is READ, never sourced, so a corrupted config cannot
# execute code.

# Populated on first use by rclone_rc_load_credentials; cached thereafter so a
# 2-second polling loop does not re-read the file on every tick.
_RCLONE_RC_USER=""
_RCLONE_RC_PASS=""
_RCLONE_RC_LOADED=""

# Path to the credential file generated by play-rclone.yml. Overridable for
# testing; there is no reason to change it in normal use.
: "${RCLONE_RC_AUTH_FILE:=$HOME/.config/rclone/rc-auth.env}"

# Load the RC credential, or fail with the play to run.
#
# Deliberately has NO unauthenticated fallback. An absent or empty credential
# means the mount was never deployed by the current play-rclone.yml, which is
# an IaC gap to fix — not a runtime condition to engineer around. Falling back
# would turn a precise 401 into a misleading "remote control not responding".
#
# stdout: nothing. Diagnostics go to stderr; the exit status carries the result.
rclone_rc_load_credentials() {
    if [ -n "$_RCLONE_RC_LOADED" ]; then
        return 0
    fi

    if [ ! -r "$RCLONE_RC_AUTH_FILE" ]; then
        echo "ERROR: rclone RC credential file not found: $RCLONE_RC_AUTH_FILE" >&2
        echo "  The rclone remote control requires authentication, so every" >&2
        echo "  rc call fails without it. It is generated by play-rclone.yml." >&2
        echo "  Deploy it with:" >&2
        echo "    ansible-playbook playbooks/imports/optional/common/play-rclone.yml" >&2
        echo "  Do NOT create it by hand." >&2
        return 1
    fi

    _RCLONE_RC_USER=$(awk -F= '$1 == "RCLONE_RC_USER" { print $2 }' "$RCLONE_RC_AUTH_FILE")
    _RCLONE_RC_PASS=$(awk -F= '$1 == "RCLONE_RC_PASS" { print $2 }' "$RCLONE_RC_AUTH_FILE")

    if [ -z "$_RCLONE_RC_USER" ] || [ -z "$_RCLONE_RC_PASS" ]; then
        echo "ERROR: $RCLONE_RC_AUTH_FILE has no RCLONE_RC_USER/RCLONE_RC_PASS value." >&2
        echo "  An empty password is not a working credential — the mount would" >&2
        echo "  refuse every request, authenticated or not." >&2
        echo "  Regenerate it with:" >&2
        echo "    ansible-playbook playbooks/imports/optional/common/play-rclone.yml" >&2
        return 1
    fi

    _RCLONE_RC_LOADED=1
    return 0
}

# Run an authenticated `rclone rc` call.
#
# Takes exactly the arguments `rclone rc` takes (--url=…, the endpoint, and any
# key=value parameters). stdout is the rclone response — the payload a caller
# captures — so nothing else is ever written there.
rclone_rc() {
    rclone_rc_load_credentials || return 1
    RCLONE_USER="$_RCLONE_RC_USER" RCLONE_PASS="$_RCLONE_RC_PASS" rclone rc "$@"
}

# True when the RC at the given address answers an authenticated call.
#
# Probes core/stats — the endpoint the polling loops actually use — rather than
# a livecheck endpoint they do not, so a pass here means the caller's real work
# will connect. Suppresses only this probe's own output; the caller prints its
# own message, and rclone_rc_load_credentials has already explained any
# credential problem on stderr.
rclone_rc_available() {
    local url="$1"
    local out
    if out=$(rclone_rc --url="$url" core/stats 2>&1); then
        return 0
    fi
    echo "  rc probe failed: $out" >&2
    return 1
}
