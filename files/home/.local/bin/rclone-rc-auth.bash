# shellcheck shell=bash
#
# rclone remote-control credentials — SOURCED LIBRARY, never executed.
#
# Source it, then call `rclone_rc` wherever you would have called `rclone rc`:
#
#     . "$HOME/.local/bin/rclone-rc-auth.bash"
#     json=$(rclone_rc --url="http://localhost:5572" vfs/stats) || exit 1
#
# WHY THIS EXISTS
# ---------------
# Plan 00094 gave the mount units --rc-user/--rc-pass (supplied as
# RCLONE_RC_USER/RCLONE_RC_PASS through a systemd EnvironmentFile). It did so
# believing that core/stats and vfs/stats "answer unauthenticated" and that
# only the vfs/refresh caller needed migrating. That premise is FALSE: once a
# credential is configured, rclone gates EVERY rc endpoint, and an
# unauthenticated call gets HTTP 401. Every un-migrated client broke silently.
#
# The migration was then hand-copied into two scripts and missed in two more.
# This library exists so there is ONE place that knows how to authenticate —
# the divergence was the defect, so a fourth copy of the block would have
# reproduced its cause.
#
# CREDENTIALS GO IN THE ENVIRONMENT, NOT IN argv
# ----------------------------------------------
# The client-side flags are --user/--pass (note: differently named from the
# server-side --rc-user/--rc-pass). Passing them on the command line puts the
# password in `ps` output for every user on the box. rclone maps each flag to
# an RCLONE_<FLAG> environment variable, so --user/--pass are driven by
# RCLONE_USER/RCLONE_PASS instead, scoped to the single child process.
#
# The credential file is READ, never sourced, so a corrupted config cannot
# execute code.

# Populated on first use by rclone_rc_load_credentials; cached thereafter so a
# 2-second polling loop does not re-read the file on every tick.
_RCLONE_RC_USER=""
_RCLONE_RC_PASS=""
_RCLONE_RC_LOADED=""

# Path to the credential file generated by play-rclone.yml. Overridable for
# testing; there is no reason to change it in normal use.
: "${RCLONE_RC_AUTH_FILE:=$HOME/.config/rclone/rc-auth.env}"

# Load the RC credential, or fail with the play to run.
#
# Deliberately has NO unauthenticated fallback. An absent or empty credential
# means the mount was never deployed by the current play-rclone.yml, which is
# an IaC gap to fix — not a runtime condition to engineer around. Falling back
# would turn a precise 401 into a misleading "remote control not responding".
#
# stdout: nothing. Diagnostics go to stderr; the exit status carries the result.
rclone_rc_load_credentials() {
    if [ -n "$_RCLONE_RC_LOADED" ]; then
        return 0
    fi

    if [ ! -r "$RCLONE_RC_AUTH_FILE" ]; then
        echo "ERROR: rclone RC credential file not found: $RCLONE_RC_AUTH_FILE" >&2
        echo "  The rclone remote control requires authentication, so every" >&2
        echo "  rc call fails without it. It is generated by play-rclone.yml." >&2
        echo "  Deploy it with:" >&2
        echo "    ansible-playbook playbooks/imports/optional/common/play-rclone.yml" >&2
        echo "  Do NOT create it by hand." >&2
        return 1
    fi

    # Everything after the FIRST `=` is the value. `print $2` would truncate at
    # the second one, and the truncated password surfaces as a 401 — which in
    # this codebase reads as a credential mismatch and sends the reader looking
    # in the wrong place. Today's generated password is alphanumeric, but
    # nothing links this parser to that constraint and the comment above
    # explicitly invites overriding RCLONE_RC_AUTH_FILE.
    _RCLONE_RC_USER=$(awk -F= '$1 == "RCLONE_RC_USER" { print substr($0, index($0, "=") + 1) }' "$RCLONE_RC_AUTH_FILE")
    _RCLONE_RC_PASS=$(awk -F= '$1 == "RCLONE_RC_PASS" { print substr($0, index($0, "=") + 1) }' "$RCLONE_RC_AUTH_FILE")

    if [ -z "$_RCLONE_RC_USER" ] || [ -z "$_RCLONE_RC_PASS" ]; then
        echo "ERROR: $RCLONE_RC_AUTH_FILE has no RCLONE_RC_USER/RCLONE_RC_PASS value." >&2
        echo "  An empty password is not a working credential — the mount would" >&2
        echo "  refuse every request, authenticated or not." >&2
        echo "  Regenerate it with:" >&2
        echo "    ansible-playbook playbooks/imports/optional/common/play-rclone.yml" >&2
        return 1
    fi

    _RCLONE_RC_LOADED=1
    return 0
}

# Run an authenticated `rclone rc` call.
#
# Takes exactly the arguments `rclone rc` takes (--url=…, the endpoint, and any
# key=value parameters). stdout is the rclone response — the payload a caller
# captures — so nothing else is ever written there.
rclone_rc() {
    rclone_rc_load_credentials || return 1
    RCLONE_USER="$_RCLONE_RC_USER" RCLONE_PASS="$_RCLONE_RC_PASS" rclone rc "$@"
}

# True when the RC at the given address answers an authenticated call.
#
# Probes core/stats — the endpoint the polling loops actually use — rather than
# a livecheck endpoint they do not, so a pass here means the caller's real work
# will connect. Suppresses only this probe's own output; the caller prints its
# own message, and rclone_rc_load_credentials has already explained any
# credential problem on stderr.
rclone_rc_available() {
    local url="$1"
    local out
    if out=$(rclone_rc --url="$url" core/stats 2>&1); then
        return 0
    fi
    echo "  rc probe failed: $out" >&2
    return 1
}

# The RC address of the rclone mount serving <mountpoint>, read from that
# process's own command line. Empty (and non-zero) when no such mount is found
# or it was started without --rc-addr.
#
# THE DEFAULT PORT IS NOT A DEFAULT ANY MORE. `play-rclone.yml` gives each mount
# `rclone_rc_port_base + mount_index`, so 5572 belongs to the FIRST mount only —
# a client assuming it talks to the wrong mount's RC on every other one, and the
# failure is silent: it preflights against a live RC and then polls that mount's
# vfs/stats for a copy happening somewhere else. Asking the process is the only
# answer that stays right when a mount is added.
#
# `rclone-cache-status` and `rclone-tail` carry their own richer form of this
# walk because they also need --cache-dir per mount; converting them onto this
# is worth doing and is not free, so it is named here rather than left implicit.
rclone_rc_addr_for_mount() {
    local mountpoint="$1"
    local pid cmdline addr

    if [ -z "$mountpoint" ]; then
        echo "rclone_rc_addr_for_mount: no mountpoint given" >&2
        return 1
    fi

    # NORMALISE TO THE MOUNT ROOT FIRST, because callers legitimately hold a path
    # INSIDE the mount rather than the mount itself — ftp-camera's find_mount_path
    # returns the target plus the remote's own path offset, which is the configured
    # case. The cmdline walk below matches the mountpoint as rclone was given it,
    # i.e. the root, so an offset path matches nothing and the caller is told no
    # mount serves a directory that is plainly inside one. Doing it here means one
    # correct answer for every caller instead of each one remembering.
    local findmnt_out=""
    if ! findmnt_out=$(findmnt -n -o TARGET --target "$mountpoint"); then
        echo "rclone_rc_addr_for_mount: $mountpoint is not inside any mount" >&2
        return 1
    fi

    # FIRST row only, and taken by parameter expansion rather than `| head -n1`.
    # `findmnt --target` emits one row per stacked mount on an over-mounted target — a
    # restarted rclone unit mounted over its own mountpoint gives exactly that shape — and
    # a two-line value can never match the cmdline below, so the caller is told no mount
    # serves a directory that plainly is one.
    #
    # The pipeline spelling is wrong HERE specifically: `ftp-camera` runs `set -e` WITHOUT
    # `pipefail`, so a failing `findmnt` piped into `head` yields exit 0 and an EMPTY
    # mount_root — and an empty mountpoint degenerates the matcher below to `*"  "*`, which
    # matches almost any argv. An expansion cannot fail silently, and the emptiness is then
    # asserted rather than assumed.
    local mount_root="${findmnt_out%%$'\n'*}"
    if [ -z "$mount_root" ]; then
        echo "rclone_rc_addr_for_mount: findmnt named no mount for $mountpoint" >&2
        return 1
    fi
    mountpoint="$mount_root"

    # `pgrep` exits 1 when nothing matches, which is a RESULT here (no mounts at
    # all) and not an error, so the loop is fed from a checked capture rather
    # than a bare substitution that would abort the caller under `set -e`.
    # Bracketed first character: an unbracketed 'rclone mount' matches this very command's
    # own argv when the caller is itself an rclone wrapper, so the walk would inspect the
    # caller and answer about the wrong process. It is the repo's rule for `pgrep -f`, and
    # the sibling walk in acceptance.bash already used it.
    local pids=""
    if ! pids=$(pgrep -f 'rclone [m]ount'); then
        echo "rclone_rc_addr_for_mount: no rclone mount process is running" >&2
        return 1
    fi

    for pid in $pids; do
        if ! cmdline=$(tr '\0' ' ' < "/proc/$pid/cmdline"); then
            # The process exited between pgrep and the read. Not this mount's
            # problem; keep looking rather than reporting a failure that says
            # nothing about the mountpoint asked for.
            continue
        fi
        case "$cmdline" in
            *" $mountpoint "* | *" $mountpoint")
                local matches
                matches=$(grep -oE -- '--rc-addr=[^ ]+' <<< "$cmdline" | cut -d= -f2)
                if [ -z "$matches" ]; then
                    echo "rclone_rc_addr_for_mount: the mount serving $mountpoint was started without --rc-addr" >&2
                    return 1
                fi
                # More than one --rc-addr is refused rather than resolved. The unit
                # template emits exactly one, so no deployed mount can reach this; a
                # second flag means a hand-edited unit, which the operator should see.
                #
                # Refused rather than "take the first" because which one rclone actually
                # listens on is NOT established here: it depends on whether the flag is
                # scalar (last wins) or a repeatable list (all bind), and nothing in this
                # repo or this plan measured it. Guessing would hand back an address the
                # mount may not answer on, and report it as discovered fact. If a
                # multi-listener unit ever turns out to be legitimate, establish the
                # semantics first and then relax this.
                if [ "$(printf '%s\n' "$matches" | wc -l)" -gt 1 ]; then
                    echo "rclone_rc_addr_for_mount: the mount serving $mountpoint has more than one --rc-addr: $(printf '%s' "$matches" | tr '\n' ' ')" >&2
                    echo "  rclone uses the last; the sibling helpers use the first. Fix the unit rather than guess." >&2
                    return 1
                fi
                addr="$matches"
                printf '%s\n' "$addr"
                return 0
                ;;
        esac
    done

    echo "rclone_rc_addr_for_mount: no rclone mount process serves $mountpoint" >&2
    return 1
}
