// Package rclonerc is the Go client of an rclone mount's remote control (RC): the credential
// play-rclone.yml writes, an authenticated `rclone rc` call, the availability probe, and the
// RC address of the mount that serves a path. It is the Go counterpart of
// files/home/.local/bin/rclone-rc-auth.bash, which the bash rclone helpers still source, and
// reads the same file the same way (SPEC-ftp-camera.md D2, E25-E28).
package rclonerc

import (
	"bufio"
	"context"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/LongTermSupport/fedora-desktop/src-go/internal/execx"
)

// Client makes RC calls. Getenv reads RCLONE_RC_AUTH_FILE and HOME; Proc is /proc.
type Client struct {
	Runner execx.Runner
	Getenv func(string) string
	Proc   fs.FS

	user, pass string
	loaded     bool
}

// advice is a failure explained for the person who has to fix it: several lines, the last of
// them the command to run, so it reads as written rather than as a wrapped error.
type advice struct{ text string }

func (a *advice) Error() string { return a.text }

func advise(format string, args ...any) error { return &advice{text: fmt.Sprintf(format, args...)} }

// AuthFile is where the credential is read from: RCLONE_RC_AUTH_FILE, or the file
// play-rclone.yml writes under the home directory.
func (c *Client) AuthFile() string {
	if p := c.Getenv("RCLONE_RC_AUTH_FILE"); p != "" {
		return p
	}
	return filepath.Join(c.Getenv("HOME"), ".config", "rclone", "rc-auth.env")
}

// Credential is the RC user and password, read once (E26). The file is data, never sourced.
func (c *Client) Credential() (string, string, error) {
	if c.loaded {
		return c.user, c.pass, nil
	}
	path := c.AuthFile()
	data, err := os.ReadFile(path)
	if err != nil {
		return "", "", advise("rclone RC credential file not found: %s\n"+
			"  The rclone remote control requires authentication, so every\n"+
			"  rc call fails without it. It is generated by play-rclone.yml.\n"+
			"  Deploy it with:\n"+
			"    ansible-playbook playbooks/imports/optional/common/play-rclone.yml\n"+
			"  Do NOT create it by hand.", path)
	}
	user, pass := firstValue(string(data), "RCLONE_RC_USER"), firstValue(string(data), "RCLONE_RC_PASS")
	if user == "" || pass == "" {
		return "", "", advise("%s has no RCLONE_RC_USER/RCLONE_RC_PASS value.\n"+
			"  An empty password is not a working credential — the mount would\n"+
			"  refuse every request, authenticated or not.\n"+
			"  Regenerate it with:\n"+
			"    ansible-playbook playbooks/imports/optional/common/play-rclone.yml", path)
	}
	c.user, c.pass, c.loaded = user, pass, true
	return user, pass, nil
}

// firstValue is the text after the first "=" of the first line whose key is key.
func firstValue(data, key string) string {
	sc := bufio.NewScanner(strings.NewReader(data))
	for sc.Scan() {
		if v, ok := strings.CutPrefix(sc.Text(), key+"="); ok {
			return v
		}
	}
	return ""
}

// Call runs `rclone rc --url=http://<addr> <endpoint>` with the credential in the child's
// environment (E27). The Result carries rclone's two streams apart.
func (c *Client) Call(ctx context.Context, addr, endpoint string) (execx.Result, error) {
	user, pass, err := c.Credential()
	if err != nil {
		return execx.Result{}, err
	}
	return c.Runner.Run(ctx, execx.Cmd{
		Name: "rclone",
		Args: []string{"rc", "--url=http://" + addr, endpoint},
		Env:  []string{"RCLONE_USER=" + user, "RCLONE_PASS=" + pass},
	})
}

// Available probes core/stats, the endpoint a copy polls (E28). Its error carries rclone's
// output, both streams.
func (c *Client) Available(ctx context.Context, addr string) error {
	res, err := c.Call(ctx, addr, "core/stats")
	if err == nil {
		return nil
	}
	out := strings.TrimRight(string(res.Stdout)+string(res.Stderr), "\n")
	if out == "" {
		out = err.Error()
	}
	return errors.New(out)
}

// AddrForMount is the --rc-addr of the rclone mount process serving the mount that contains
// path (E25).
func (c *Client) AddrForMount(ctx context.Context, path string) (string, error) {
	if path == "" {
		return "", errors.New("no mountpoint given")
	}
	res, err := c.Runner.Run(ctx, execx.Cmd{Name: "findmnt", Args: []string{"-n", "-o", "TARGET", "--target", path}})
	if err != nil {
		return "", fmt.Errorf("%s is not inside any mount", path)
	}
	root := string(res.Stdout)
	if i := strings.IndexByte(root, '\n'); i >= 0 {
		root = root[:i]
	}
	if root == "" {
		return "", fmt.Errorf("findmnt named no mount for %s", path)
	}
	mounts, err := c.mountProcesses()
	if err != nil {
		return "", err
	}
	if len(mounts) == 0 {
		return "", errors.New("no rclone mount process is running")
	}
	if args := serving(mounts, root); args != nil {
		return rcAddr(root, args)
	}
	return "", fmt.Errorf("no rclone mount process serves %s", root)
}

// MountProcess is the argument list of the first rclone mount process, in pid order, one of
// whose arguments after the program is root; nil when none is.
func (c *Client) MountProcess(root string) ([]string, error) {
	mounts, err := c.mountProcesses()
	if err != nil {
		return nil, err
	}
	return serving(mounts, root), nil
}

func serving(mounts [][]string, root string) []string {
	for _, args := range mounts {
		if slices.Contains(args[1:], root) {
			return args
		}
	}
	return nil
}

// FlagValues is the value of every `<flag>=<value>` argument with a value, in order.
func FlagValues(args []string, flag string) []string {
	var values []string
	for _, a := range args {
		if v, ok := strings.CutPrefix(a, flag+"="); ok && v != "" {
			values = append(values, v)
		}
	}
	return values
}

func rcAddr(root string, args []string) (string, error) {
	addrs := FlagValues(args, "--rc-addr")
	switch len(addrs) {
	case 0:
		return "", fmt.Errorf("the mount serving %s was started without --rc-addr", root)
	case 1:
		return addrs[0], nil
	default:
		return "", advise("the mount serving %s has more than one --rc-addr: %s\n"+
			"  Which one this mount is listening on is not established here, so no address is returned.\n"+
			"  Fix the unit to carry one --rc-addr.", root, strings.Join(addrs, " "))
	}
}

// mountProcesses is the argument list of every process whose command line contains
// "rclone mount", in pid order. A process that ends while it is read is passed over.
func (c *Client) mountProcesses() ([][]string, error) {
	entries, err := fs.ReadDir(c.Proc, ".")
	if err != nil {
		return nil, fmt.Errorf("read /proc: %w", err)
	}
	var pids []int
	for _, e := range entries {
		if pid, err := strconv.Atoi(e.Name()); err == nil {
			pids = append(pids, pid)
		}
	}
	slices.Sort(pids)
	var mounts [][]string
	for _, pid := range pids {
		data, err := fs.ReadFile(c.Proc, strconv.Itoa(pid)+"/cmdline")
		if err != nil {
			continue
		}
		args := strings.Split(strings.TrimSuffix(string(data), "\x00"), "\x00")
		if strings.Contains(strings.Join(args, " "), "rclone mount") {
			mounts = append(mounts, args)
		}
	}
	return mounts, nil
}
