// PinnedHeader opens the pinned list `pin` writes. A list without it was written by hand, and
// pin refuses to replace it rather than lose the names in it.
const PinnedHeader = `# Generated by playbooks/imports/play-git-hooks-security.yml (qa-private-names pin): the names
# this machine's inventory knows and the owner's vaulted private_name_terms. Do not edit by hand:
# the next run replaces it. Add a name with a vault-encrypted private_name_terms item.
`

// pinInputLimit bounds the input: an inventory is kilobytes.
const pinInputLimit = 4 << 20

// teamIDGrammar is a v2 team id (internal/teamchat/paths): a served state directory named
// otherwise is not a team.
var teamIDGrammar = regexp.MustCompile(`^[a-z][a-z0-9-]{0,21}$`)

// pinInput is what the play hands pin: the inventory variables, read as their entries' name
// fields only, the team directories the bus host serves, and the owner's names.
type pinInput struct {
	TeamchatTeams        []teamEntry `json:"teamchat_teams"`
	TeamchatLXCMembers   []lxcEntry  `json:"teamchat_lxc_members"`
	AgentBusTeams        []teamEntry `json:"agent_bus_teams"`
	AgentBusLXCMembers   []lxcEntry  `json:"agent_bus_lxc_members"`
	AgentBusElementTeams []teamEntry `json:"agent_bus_element_teams"`
	TeamchatSite         string      `json:"teamchat_site"`
	ServedTeams          []string    `json:"served_teams"`
	PrivateNameTerms     []string    `json:"private_name_terms"`
}

// teamEntry is the part of a team declaration that names something: the id, the display name,
// the member handles it names (the coordinator, the duties' keys), and the repositories it
// trusts (v1 keeps org, exclude and repos on the entry, v2 under trust). humans are left out:
// they are the people who watch the team, whose public logins appear in this repository by
// design. A url, a port and a network are addresses, not names.
type teamEntry struct {
	Team        string            `json:"team"`
	Name        string            `json:"name"`
	Coordinator string            `json:"coordinator"`
	Duties      map[string]string `json:"duties"`
	trustEntry
	Trust trustEntry `json:"trust"`
}

// trustEntry is a team's trusted repositories: an owner, repositories left out, owner/repo pairs.
type trustEntry struct {
	Org     string   `json:"org"`
	Exclude []string `json:"exclude"`
	Repos   []struct {
		Repo string `json:"repo"`
	} `json:"repos"`
}

// lxcEntry is the part of an LXC member declaration that names something: its container, its
// agent user, its repository and host words (v1's handle parts). The checkout is a path whose
// last word is the repository, which repo or the served handles already give.
type lxcEntry struct {
	Container string `json:"container"`
	User      string `json:"user"`
	Repo      string `json:"repo"`
	Host      string `json:"host"`
	Site      string `json:"site"`
}

// pin writes the pinned list from the inventory on stdin (Plan 00265 R79).
func (a app) pin(rest []string, out, errOut *emit.Emitter) ExitCode {
	if len(rest) != 0 {
		return fail(errOut, errors.New("pin takes no arguments; the inventory comes on stdin"))
	}
	in, err := a.readPinInput()
	if err != nil {
		return fail(errOut, err)
	}
	owner, err := ownerTerms(in.PrivateNameTerms)
	if err != nil {
		return fail(errOut, err)
	}
	root, err := a.git(nil, "rev-parse", "--show-toplevel")
	if err != nil {
		return fail(errOut, err)
	}
	common, err := a.git(nil, "rev-parse", "--path-format=absolute", "--git-common-dir")
	if err != nil {
		return fail(errOut, err)
	}
	public, err := a.public(strings.TrimSpace(root))
	if err != nil {
		return fail(errOut, err)
	}
	auto, teams := inventoryTerms(in, public)
	names := pinnedUnion(auto, owner)
	if teams > 0 && len(names) == 0 {
		return fail(errOut, fmt.Errorf("this machine has %d team(s), but none of their names is specific enough to block (at least %d characters, not only generic words); put the names to guard in private_name_terms, each item vault-encrypted", teams, MinSpecificLength))
	}
	return a.writePinned(filepath.Join(strings.TrimSpace(common), PinnedName), names, out, errOut)
}

// readPinInput decodes stdin strictly: an unknown key is a misspelt variable, and a half-read
// inventory would drop names. A decode error names its kind and offset, never the input.
func (a app) readPinInput() (pinInput, error) {
	data, err := stdinread.Read(a.env.Stdin, stdinread.Options{Prog: "qa-private-names pin", Err: a.env.Stderr, Limit: pinInputLimit, GiveUpAfter: stdinread.PipedGiveUp, Clock: a.env.Clock})
	if err != nil {
		return pinInput{}, err
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	var top map[string]json.RawMessage
	if err := dec.Decode(&top); err != nil {
		return pinInput{}, fmt.Errorf("the pin input is not the inventory JSON pin reads: %s", decodeProblem(err))
	}
	if _, err := dec.Token(); !errors.Is(err, io.EOF) {
		return pinInput{}, errors.New("the pin input holds more than one JSON value")
	}
	for _, k := range slices.Sorted(maps.Keys(top)) {
		if !slices.Contains(pinInputKeys, k) {
			return pinInput{}, fmt.Errorf("the pin input names %q, an inventory variable pin does not read (it reads %s)", k, strings.Join(pinInputKeys, ", "))
		}
	}
	var in pinInput
	if err := json.Unmarshal(data, &in); err != nil {
		return pinInput{}, fmt.Errorf("the pin input is not the inventory JSON pin reads: %s", decodeProblem(err))
	}
	return in, nil
}

// pinInputKeys are pinInput's JSON keys: the only ones the input may hold.
var pinInputKeys = []string{
	"agent_bus_element_teams", "agent_bus_lxc_members", "agent_bus_teams", "private_name_terms",
	"served_teams", "teamchat_lxc_members", "teamchat_site", "teamchat_teams",
}

// decodeProblem says what is wrong with the input without quoting it.
func decodeProblem(err error) string {
	var syntax *json.SyntaxError
	var typ *json.UnmarshalTypeError
	switch {
	case errors.As(err, &syntax):
		return "not JSON at byte " + strconv.FormatInt(syntax.Offset, 10)
	case errors.As(err, &typ):
		return "a " + typ.Value + " where field " + typ.Field + " needs a " + typ.Type.String()
	case errors.Is(err, io.EOF), errors.Is(err, io.ErrUnexpectedEOF):
		return "it ends early"
	}
	return "it cannot be decoded"
}

// ownerTerms are the owner's names as written, each one line the guard reads back as one name:
// an item that is blank, holds a line break, or starts with # (a comment to the guard) is
// refused by its position, never its value.
func ownerTerms(items []string) ([]string, error) {
	out := make([]string, 0, len(items))
	for i, item := range items {
		name := strings.TrimSpace(item)
		if name == "" || strings.ContainsAny(name, "\r\n") || strings.HasPrefix(name, "#") {
			return nil, fmt.Errorf("private_name_terms item %d is not one name on one line (blank, a line break, or a leading #)", i+1)
		}
		out = append(out, name)
	}
	return out, nil
}

// inventoryTerms are the names the inventory knows, each held to the rule a learned bus name is
// (Derive's: specific, not public), and how many teams the machine has.
func inventoryTerms(in pinInput, public []string) ([]string, int) {
	pub := map[string]bool{}
	for _, p := range public {
		pub[strings.ToLower(strings.TrimSpace(p))] = true
	}
	d := &deriver{public: pub, seen: map[string]bool{}}
	teams := 0
	for _, list := range [][]teamEntry{in.TeamchatTeams, in.AgentBusTeams, in.AgentBusElementTeams} {
		for _, t := range list {
			teams++
			d.add(SourceTeam, t.Team)
			d.add(SourceTeam, t.Name)
			if t.Coordinator != "" {
				d.handle(t.Coordinator)
			}
			for h := range t.Duties {
				d.handle(h)
			}
			d.trust(t.trustEntry)
			d.trust(t.Trust)
		}
	}
	for _, list := range [][]lxcEntry{in.TeamchatLXCMembers, in.AgentBusLXCMembers} {
		for _, m := range list {
			for _, n := range []string{m.Container, m.User, m.Repo, m.Host, m.Site} {
				d.add(SourceMember, n)
			}
		}
	}
	d.add(SourceMember, in.TeamchatSite)
	for _, s := range in.ServedTeams {
		if teamIDGrammar.MatchString(s) {
			teams++
			d.add(SourceTeam, s)
		}
	}
	out := make([]string, 0, len(d.out))
	for _, t := range d.out {
		out = append(out, t.Text)
	}
	return out, teams
}

// trust adds a team's trusted owner, left-out repositories, and each owner/repo's two words.
func (d *deriver) trust(tr trustEntry) {
	d.add(SourceTeam, tr.Org)
	for _, x := range tr.Exclude {
		d.add(SourceTeam, x)
	}
	for _, r := range tr.Repos {
		owner, repo, _ := strings.Cut(r.Repo, "/")
		d.add(SourceTeam, owner)
		d.add(SourceTeam, repo)
	}
}

// pinnedUnion is both lists without duplicates (case-folded, the owner's spelling first), sorted
// case-insensitively.
func pinnedUnion(auto, owner []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, n := range append(append([]string(nil), owner...), auto...) {
		if k := strings.ToLower(n); !seen[k] {
			seen[k] = true
			out = append(out, n)
		}
	}
	sort.Slice(out, func(i, j int) bool {
		li, lj := strings.ToLower(out[i]), strings.ToLower(out[j])
		if li != lj {
			return li < lj
		}
		return out[i] < out[j]
	})
	return out
}

// pinnedState prints what the pinned list is, by writePinned's own header test: absent,
// generated, or hand-written (one pin refuses). Its content is never printed.
func (a app) pinnedState(rest []string, out, errOut *emit.Emitter) ExitCode {
	if len(rest) != 0 {
		return fail(errOut, errors.New("pinned-state takes no arguments"))
	}
	common, err := a.git(nil, "rev-parse", "--path-format=absolute", "--git-common-dir")
	if err != nil {
		return fail(errOut, err)
	}
	old, err := a.env.ReadFile(filepath.Join(strings.TrimSpace(common), PinnedName))
	switch {
	case errors.Is(err, fs.ErrNotExist):
		out.Line("absent")
	case err != nil:
		return fail(errOut, fmt.Errorf("the pinned list %s is unreadable: %w", PinnedName, err))
	case strings.HasPrefix(string(old), PinnedHeader):
		out.Line("generated")
	default:
		out.Line("hand-written")
	}
	return ExitOK
}

// writePinned replaces the pinned list whole, unless it is unchanged; a list written by hand is
// refused, since replacing it would lose the owner's names. Only the count is printed.
func (a app) writePinned(path string, names []string, out, errOut *emit.Emitter) ExitCode {
	text := PinnedHeader + strings.Join(names, "\n")
	if len(names) > 0 {
		text += "\n"
	}
	old, err := a.env.ReadFile(path)
	switch {
	case errors.Is(err, fs.ErrNotExist):
	case err != nil:
		return fail(errOut, fmt.Errorf("the pinned list %s is unreadable: %w", PinnedName, err))
	case !strings.HasPrefix(string(old), PinnedHeader):
		return fail(errOut, fmt.Errorf("<git dir>/%s was written by hand, so it is not replaced: move each name in it into private_name_terms in host_vars (one vault-encrypted item per name), delete the file, and run the play again", PinnedName))
	case string(old) == text:
		out.Line("private-names: pinned list unchanged (" + strconv.Itoa(len(names)) + " names)")
		return ExitOK
	}
	if err := a.env.ReplaceFile(path, []byte(text)); err != nil {
		return fail(errOut, fmt.Errorf("the pinned list cannot be written: %w", err))
	}
	out.Line("private-names: pinned list written (" + strconv.Itoa(len(names)) + " names)")
	return ExitOK
}
