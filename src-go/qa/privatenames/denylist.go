package privatenames

import (
	"errors"
	"fmt"
	"io/fs"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/LongTermSupport/fedora-desktop/src-go/qa/internal/emit"
)

// The denylist mode writes the terms that block a commit as go-qa-ci's public-safety denylist:
// one extended regular expression per line, which that scan matches with `grep -E -i`. The file
// is derived from the same term list and rule as every scan here, never written by hand.

// denylistHeader is the file's first line. It names the mode, never a term.
const denylistHeader = "# Generated by `qa-private-names.bash denylist FILE`: the terms that block a commit, one ERE per line. Do not edit by hand.\n"

// The ERE edges equal the matcher's leftEdge and rightEdge: a letter, digit or underscore may not
// touch a term, anything else (a hyphen, dot, slash, space) may.
const (
	ereLeftEdge  = `(^|[^[:alnum:]_])`
	ereRightEdge = `([^[:alnum:]_]|$)`
)

// ereMeta are the characters special in a POSIX extended regular expression.
const ereMeta = `\.[]()*+?{}|^$`

// DenylistPattern is the ERE that grep -E -i matches a term with, as the matcher does.
func DenylistPattern(term string) string {
	var b strings.Builder
	b.WriteString(ereLeftEdge)
	for _, r := range term {
		if strings.ContainsRune(ereMeta, r) {
			b.WriteByte('\\')
		}
		b.WriteRune(r)
	}
	b.WriteString(ereRightEdge)
	return b.String()
}

// denylist writes the blocking terms to one new file outside every work tree of this repository.
// The path is judged before the terms are learned, so a refused run writes nothing.
func (a app) denylist(args []string, errOut *emit.Emitter) ExitCode {
	if len(args) != 1 || args[0] == "" {
		return fail(errOut, errors.New("denylist needs exactly one FILE, outside this repository"))
	}
	target, err := a.denylistTarget(args[0])
	if err != nil {
		return fail(errOut, err)
	}
	terms, code, ok := a.terms(errOut)
	if !ok {
		return code
	}
	if len(terms) == 0 {
		return fail(errOut, errors.New("no terms to write: no agent bus, no host name and no term list here, and a denylist must not be empty"))
	}
	var b strings.Builder
	b.WriteString(denylistHeader)
	for _, t := range terms {
		b.WriteString(DenylistPattern(t.Text) + "\n")
	}
	if err := a.env.CreateFile(target, []byte(b.String())); err != nil {
		if errors.Is(err, fs.ErrExist) {
			return fail(errOut, errors.New("the denylist FILE exists; it is never overwritten"))
		}
		return fail(errOut, fmt.Errorf("the denylist cannot be written: %w", err))
	}
	errOut.Line("private-names: " + strconv.Itoa(len(terms)) + " terms written")
	return ExitOK
}

// denylistTarget is FILE made absolute, its directory's links resolved, refused when it lies in
// any work tree of this repository (where it could be committed, and where the scan would read it).
func (a app) denylistTarget(file string) (string, error) {
	abs := file
	if !filepath.IsAbs(abs) {
		abs = filepath.Join(a.env.Cwd, abs)
	}
	abs = filepath.Clean(abs)
	dir, err := a.env.EvalSymlinks(filepath.Dir(abs))
	if err != nil {
		return "", fmt.Errorf("the denylist FILE's directory cannot be resolved: %w", err)
	}
	target := filepath.Join(dir, filepath.Base(abs))
	list, err := a.git(nil, "worktree", "list", "--porcelain")
	if err != nil {
		return "", err
	}
	for line := range strings.SplitSeq(list, "\n") {
		tree, found := strings.CutPrefix(line, "worktree ")
		if !found {
			continue
		}
		tree = filepath.Clean(tree)
		prefix := strings.TrimSuffix(tree, string(filepath.Separator)) + string(filepath.Separator)
		if target == tree || strings.HasPrefix(target, prefix) {
			return "", errors.New("the denylist FILE is inside a work tree of this repository; write it outside the repository")
		}
	}
	return target, nil
}
